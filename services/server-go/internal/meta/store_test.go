// newBoltForTest opens a fresh database in a not-yet-existing directory
// (exercising parent creation). fsync is disabled for speed; it does not
// change semantics.
func newBoltForTest(t *testing.T) domain.MetaStore {
	path := filepath.Join(t.TempDir(), "nested", "meta.db")
	s, err := NewBolt(path)
	if err != nil {
		t.Fatalf("NewBolt: %v", err)
	}
	s.db.NoSync = true
	t.Cleanup(func() { _ = s.Close() })
	return s
}

