// dump reads every record back through the public API.
func dump(t *testing.T, s domain.MetaStore) map[string]any {
	t.Helper()
	ctx := context.Background()
	out := map[string]any{}
	get := func(name string, v any, err error) {
		t.Helper()
		if err != nil {
			t.Fatalf("dump %s: %v", name, err)
		}
		out[name] = v
	}
	v1, err := s.ListTenants(ctx)
	get("tenants", v1, err)
	v2, err := s.ListAccounts(ctx)
	get("accounts", v2, err)
	v3, err := s.ListTenantMembers(ctx, "t1")
	get("members", v3, err)
	v4, err := s.ListAccountMemberships(ctx, "a1")
	get("memberships", v4, err)
	v5, err := s.ListTokens(ctx, "a1")
	get("tokens", v5, err)
	v6, err := s.GetTokenByHash(ctx, "hash1")
	get("tokenByHash", v6, err)
	v7, err := s.ListTrees(ctx, "")
	get("trees", v7, err)
	v8, err := s.ListBranches(ctx, "tr1")
	for i := range v8 {
		v8[i].UpdatedAt = time.Time{} // store-managed "now"
	}
	get("branches", v8, err)
	v9, err := s.GetSnapshot(ctx, "s1")
	get("s1", v9, err)
	v10, err := s.GetSnapshot(ctx, "s2")
	get("s2", v10, err)
	v11, err := s.CountSnapshots(ctx, "")
	get("snapCount", v11, err)
	v12, err := s.ListTags(ctx, "tr1")
	get("tags", v12, err)
	v13, err := s.ListStaged(ctx, "tr1", "")
	get("staged", v13, err)
	v14, err := s.ListProtections(ctx, "tr1")
	get("protections", v14, err)
	v15, err := s.ListMergeRequests(ctx, "tr1", "")
	get("mrs", v15, err)
	v16, err := s.ListAudit(ctx, domain.AuditFilter{})
	get("audit", v16, err)
	v17, err := s.ListLicenseRules(ctx, "tr1")
	get("licenses", v17, err)
	v18, err := s.GetAccessConfig(ctx, "t1", "roles")
	get("access", v18, err)
	v19, err := s.CountStaged(ctx)
	get("stagedCount", v19, err)
	v20, err := NewHistory(s).Missing(ctx, "s2", nil)
	get("history", v20, err)
	return out
}

// TestStoresAgree feeds the same script to Memory and Bolt and requires
// byte-for-byte identical results through the public API.
func TestStoresAgree(t *testing.T) {
	mem, bdb := newMemoryForTest(t), newBoltForTest(t)
	populate(t, mem)
	populate(t, bdb)
	dm, db := dump(t, mem), dump(t, bdb)
	for k := range dm {
		wantEqual(t, "stores disagree on "+k, db[k], dm[k])
	}
}

func TestBoltPersistence(t *testing.T) {
	ctx := context.Background()
	path := filepath.Join(t.TempDir(), "meta.db")
	s, err := NewBolt(path)
	if err != nil {
		t.Fatal(err)
	}
	if s.Path() != path {
		t.Fatalf("Path() = %q, want %q", s.Path(), path)
	}
	populate(t, s)
	before := dump(t, s)
	must(t, s.Close())

	s2, err := NewBolt(path)
	if err != nil {
		t.Fatalf("reopen: %v", err)
	}
	defer s2.Close()
	after := dump(t, s2)
	for k := range before {
		wantEqual(t, "after reopen "+k, after[k], before[k])
	}
	// Secrets hidden from JSON in the domain types survive.
	a, err := s2.GetAccountByUsername(ctx, "alice")
	must(t, err)
	if a.PasswordHash != "ph" {
		t.Fatalf("PasswordHash after reopen = %q", a.PasswordHash)
	}
	// Counters continue where they left off.
	mr := &domain.MergeRequest{TreeID: "tr1"}
	must(t, s2.CreateMergeRequest(ctx, mr))
	if mr.Number != 3 {
		t.Fatalf("MR number after reopen = %d, want 3", mr.Number)
	}
	if n, err := s2.CountSnapshots(ctx, "tr1"); err != nil || n != 2 {
		t.Fatalf("CountSnapshots after reopen = %d, %v", n, err)
	}
	// Audit ordering is preserved and new events sort after old ones.
	must(t, s2.AppendAudit(ctx, &domain.AuditEvent{ID: "e3", Action: "x", At: at(22)}))
	evs, err := s2.ListAudit(ctx, domain.AuditFilter{})
	must(t, err)
	if len(evs) != 3 || evs[0].ID != "e3" || evs[2].ID != "e1" {
		t.Fatalf("audit after reopen: %+v", evs)
	}
	// Unique indexes survive.
	wantErr(t, s2.CreateTenant(ctx, &domain.Tenant{Slug: "acme"}), domain.ErrAlreadyExists)
	wantErr(t, s2.CompareAndSwapBranchTip(ctx, "tr1", "main", "", "x"), domain.ErrConflict)
	must(t, s2.CompareAndSwapBranchTip(ctx, "tr1", "main", "s2", "s3"))
}

func TestBoltRejectsUnknownSchema(t *testing.T) {
	path := filepath.Join(t.TempDir(), "meta.db")
	s, err := NewBolt(path)
	if err != nil {
		t.Fatal(err)
	}
	err = s.db.Update(func(tx *bolt.Tx) error {
		return tx.Bucket(bktMeta).Put([]byte("schema"), []byte("99"))
	})
	must(t, err)
	must(t, s.Close())
	if s2, err := NewBolt(path); err == nil {
		_ = s2.Close()
		t.Fatal("NewBolt accepted an unknown schema version")
	}
}

