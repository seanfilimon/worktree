// This file holds the domain <-> syncpb conversions. Functions named
// *FromPB validate their input and return errors suitable for wrapping in an
// InvalidArgument status; *ToPB functions never fail.

// hashFromPB decodes a ContentHash, requiring exactly hash.Size bytes.
func hashFromPB(h *syncpb.ContentHash) (hash.Hash, error) {
	v := h.GetValue()
	if len(v) != hash.Size {
		return hash.Hash{}, fmt.Errorf("content hash must be %d bytes, got %d", hash.Size, len(v))
	}
	return hash.Hash(v), nil
}

// hashToPB encodes h as a ContentHash.
func hashToPB(h hash.Hash) *syncpb.ContentHash {
	return &syncpb.ContentHash{Value: h[:]}
}

// hashesToPB encodes a list of hashes.
func hashesToPB(hs []hash.Hash) []*syncpb.ContentHash {
	out := make([]*syncpb.ContentHash, len(hs))
	for i, h := range hs {
		out[i] = hashToPB(h)
	}
	return out
}

// tsToPB converts t to a Timestamp; the zero time becomes nil.
func tsToPB(t time.Time) *timestamppb.Timestamp {
	if t.IsZero() {
		return nil
	}
	return timestamppb.New(t)
}

// tsFromPB converts ts to a UTC time; nil (or an invalid timestamp) yields
// the zero time.
func tsFromPB(ts *timestamppb.Timestamp) time.Time {
	if ts == nil || ts.CheckValid() != nil {
		return time.Time{}
	}
	return ts.AsTime().UTC()
}

// snapshotIDToPB wraps id; "" becomes nil (for optional fields).
func snapshotIDToPB(id string) *syncpb.SnapshotId {
	if id == "" {
		return nil
	}
	return &syncpb.SnapshotId{Value: id}
}

// snapshotFromPB validates a SnapshotRecord and converts it to a
// domain.Snapshot. PushedBy / PushedAt are left for the caller to fill.
func snapshotFromPB(r *syncpb.SnapshotRecord) (domain.Snapshot, error) {
	id := r.GetId().GetValue()
	if !validID(id) {
		return domain.Snapshot{}, fmt.Errorf("snapshot id %q is missing or malformed", id)
	}
	mh, err := hashFromPB(r.GetManifestHash())
	if err != nil {
		return domain.Snapshot{}, fmt.Errorf("snapshot %s: manifest_hash: %v", id, err)
	}
	parents := make([]string, 0, len(r.GetParents()))
	seen := make(map[string]struct{}, len(r.GetParents()))
	for _, p := range r.GetParents() {
		pid := p.GetValue()
		if !validID(pid) {
			return domain.Snapshot{}, fmt.Errorf("snapshot %s: parent id %q is malformed", id, pid)
		}
		if pid == id {
			return domain.Snapshot{}, fmt.Errorf("snapshot %s lists itself as a parent", id)
		}
		if _, dup := seen[pid]; dup {
			return domain.Snapshot{}, fmt.Errorf("snapshot %s lists parent %s twice", id, pid)
		}
		seen[pid] = struct{}{}
		parents = append(parents, pid)
	}
	return domain.Snapshot{
		ID:            id,
		TreeID:        r.GetTreeId().GetValue(),
		BranchName:    r.GetBranchName(),
		Parents:       parents,
		ManifestHash:  mh,
		Author:        r.GetAuthor(),
		Message:       r.GetMessage(),
		CreatedAt:     tsFromPB(r.GetCreatedAt()),
		AutoGenerated: r.GetAutoGenerated(),
		Dependencies:  dependenciesFromPB(r.GetDependencies()),
		Reverts:       r.GetReverts().GetValue(),
		Signature:     r.GetSignature(),
		SigningKeyID:  r.GetSigningKeyId(),
	}, nil
}

// dependenciesFromPB converts declared dependencies (nil when none).
func dependenciesFromPB(in []*syncpb.Dependency) []domain.Dependency {
	if len(in) == 0 {
		return nil
	}
	out := make([]domain.Dependency, len(in))
	for i, d := range in {
		out[i] = domain.Dependency{
			TenantSlug: d.GetTenantSlug(),
			Tree:       d.GetTree(),
			Branch:     d.GetBranch(),
			Title:      d.GetTitle(),
			Details:    d.GetDetails(),
			Priority:   d.GetPriority(),
			Blocking:   d.GetBlocking(),
			Linked:     d.GetLinked(),
		}
	}
	return out
}

// dependenciesToPB is the inverse of dependenciesFromPB.
func dependenciesToPB(in []domain.Dependency) []*syncpb.Dependency {
	if len(in) == 0 {
		return nil
	}
	out := make([]*syncpb.Dependency, len(in))
	for i, d := range in {
		out[i] = &syncpb.Dependency{
			TenantSlug: d.TenantSlug,
			Tree:       d.Tree,
			Branch:     d.Branch,
			Title:      d.Title,
			Details:    d.Details,
			Priority:   d.Priority,
			Blocking:   d.Blocking,
			Linked:     d.Linked,
		}
	}
	return out
}

// snapshotToPB converts a stored snapshot to its wire record.
func snapshotToPB(s *domain.Snapshot) *syncpb.SnapshotRecord {
	parents := make([]*syncpb.SnapshotId, len(s.Parents))
	for i, p := range s.Parents {
		parents[i] = &syncpb.SnapshotId{Value: p}
	}
	return &syncpb.SnapshotRecord{
		Id:            &syncpb.SnapshotId{Value: s.ID},
		TreeId:        &syncpb.TreeId{Value: s.TreeID},
		BranchName:    s.BranchName,
		Parents:       parents,
		ManifestHash:  hashToPB(s.ManifestHash),
		Author:        s.Author,
		Message:       s.Message,
		CreatedAt:     tsToPB(s.CreatedAt),
		AutoGenerated: s.AutoGenerated,
		Dependencies:  dependenciesToPB(s.Dependencies),
		Reverts:       snapshotIDToPB(s.Reverts),
		Signature:     s.Signature,
		SigningKeyId:  s.SigningKeyID,
	}
}

// sameSnapshotContent reports whether a and b describe the same snapshot,
// ignoring server-assigned push metadata (PushedBy, PushedAt) and the
// informational branch name.
func sameSnapshotContent(a, b *domain.Snapshot) bool {
	if a.ID != b.ID || a.TreeID != b.TreeID || a.ManifestHash != b.ManifestHash || len(a.Parents) != len(b.Parents) {
		return false
	}
	for i := range a.Parents {
		if a.Parents[i] != b.Parents[i] {
			return false
		}
	}
	return true
}

// branchToPB converts a branch.
func branchToPB(b *domain.Branch) *syncpb.BranchInfo {
	return &syncpb.BranchInfo{
		Name:      b.Name,
		Tip:       snapshotIDToPB(b.Tip),
		Protected: b.Protected,
		UpdatedAt: tsToPB(b.UpdatedAt),
	}
}

// tagToPB converts a tag.
func tagToPB(t *domain.Tag) *syncpb.TagRecord {
	rec := &syncpb.TagRecord{
		Name:      t.Name,
		Target:    &syncpb.SnapshotId{Value: t.Target},
		Tagger:    t.Tagger,
		CreatedAt: tsToPB(t.CreatedAt),
	}
	if t.Message != "" {
		rec.Message = proto.String(t.Message)
	}
	return rec
}

// stagedToPB converts a staged snapshot.
func stagedToPB(s *domain.StagedSnapshot) *syncpb.StagedInfo {
	info := &syncpb.StagedInfo{
		SnapshotId:    &syncpb.SnapshotId{Value: s.SnapshotID},
		Author:        s.Author,
		BranchName:    s.BranchName,
		FilesChanged:  append([]string(nil), s.FilesChanged...),
		FilesAdded:    s.FilesAdded,
		FilesModified: s.FilesModified,
		FilesDeleted:  s.FilesDeleted,
		StagedAt:      tsToPB(s.StagedAt),
	}
	if s.Message != "" {
		info.Message = proto.String(s.Message)
	}
	if h, err := hash.FromHex(s.ManifestHash); err == nil {
		info.ManifestHash = hashToPB(h)
	}
	return info
}

// treeToPB converts a tree plus its tenant slug.
func treeToPB(t *domain.Tree, tenantSlug string, created bool) *syncpb.TreeInfo {
	return &syncpb.TreeInfo{
		TreeId:        &syncpb.TreeId{Value: t.ID},
		TenantId:      &syncpb.TenantId{Value: t.TenantID},
		TenantSlug:    tenantSlug,
		Name:          t.Name,
		DefaultBranch: t.DefaultBranch,
		Created:       created,
	}
}
