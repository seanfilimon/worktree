// Package domain holds the server's shared data model and the service
// interfaces that the other internal packages implement and consume.
//
// This package is the contract between internal/meta, internal/iam,
// internal/syncsvc, internal/httpapi, internal/review, internal/audit,
// internal/license, internal/events and internal/staged. It must stay free
// of imports from those packages.
package domain

import (
	"errors"
	"time"

	"github.com/seanfilimon/worktree/services/server-go/internal/hash"
)

// Sentinel errors. Implementations wrap these with fmt.Errorf("...: %w", ErrX)
// so callers can test with errors.Is.
var (
	ErrNotFound        = errors.New("not found")
	ErrAlreadyExists   = errors.New("already exists")
	ErrConflict        = errors.New("conflict")
	ErrUnauthenticated = errors.New("unauthenticated")
	ErrForbidden       = errors.New("forbidden")
	ErrInvalid         = errors.New("invalid argument")
)

// Built-in roles, ordered from most to least privileged. Names match
// worktree-protocol's iam::role built-ins (lower-cased).
const (
	RoleOwner      = "owner"
	RoleAdmin      = "admin"
	RoleMaintainer = "maintainer"
	RoleDeveloper  = "developer"
	RoleViewer     = "viewer"
)

// Tenant kinds.
const (
	TenantUser = "user"
	TenantOrg  = "org"
)

// Tree visibility.
const (
	VisibilityPrivate  = "private"  // members of the tenant only
	VisibilityInternal = "internal" // any authenticated account
	VisibilityPublic   = "public"   // anyone, including anonymous reads
)

// Merge request states.
const (
	MRStateOpen   = "open"
	MRStateMerged = "merged"
	MRStateClosed = "closed"
)

type Tenant struct {
	ID        string    `json:"id"`
	Slug      string    `json:"slug"` // lowercase [a-z0-9-], unique
	Name      string    `json:"name"`
	Kind      string    `json:"kind"` // TenantUser | TenantOrg
	Plan      string    `json:"plan"` // "free" | "pro" | "enterprise"
	CreatedAt time.Time `json:"created_at"`
}

type Account struct {
	ID           string    `json:"id"`
	Username     string    `json:"username"` // unique, also the slug of the personal tenant
	Email        string    `json:"email"`
	DisplayName  string    `json:"display_name"`
	PasswordHash string    `json:"-"`
	TenantID     string    `json:"tenant_id"` // personal tenant
	IsAdmin      bool      `json:"is_admin"`  // server-wide admin
	Disabled     bool      `json:"disabled"`
	CreatedAt    time.Time `json:"created_at"`
}

type Membership struct {
	TenantID  string    `json:"tenant_id"`
	AccountID string    `json:"account_id"`
	Role      string    `json:"role"`
	CreatedAt time.Time `json:"created_at"`
}

type APIToken struct {
	ID         string     `json:"id"`
	AccountID  string     `json:"account_id"`
	Name       string     `json:"name"`
	TokenHash  string     `json:"-"` // hex sha256 of the raw token
	CreatedAt  time.Time  `json:"created_at"`
	ExpiresAt  *time.Time `json:"expires_at,omitempty"`
	LastUsedAt *time.Time `json:"last_used_at,omitempty"`
}

type Tree struct {
	ID            string    `json:"id"`
	TenantID      string    `json:"tenant_id"`
	Name          string    `json:"name"` // unique within tenant
	Description   string    `json:"description"`
	DefaultBranch string    `json:"default_branch"`
	Visibility    string    `json:"visibility"`
	CreatedAt     time.Time `json:"created_at"`
	UpdatedAt     time.Time `json:"updated_at"`
}

type Branch struct {
	TreeID    string    `json:"tree_id"`
	Name      string    `json:"name"`
	Tip       string    `json:"tip"` // snapshot id; "" for an empty branch
	Protected bool      `json:"protected"`
	CreatedAt time.Time `json:"created_at"`
	UpdatedAt time.Time `json:"updated_at"`
}

type Snapshot struct {
	ID            string    `json:"id"`
	TreeID        string    `json:"tree_id"`
	BranchName    string    `json:"branch_name"`
	Parents       []string  `json:"parents"`
	ManifestHash  hash.Hash `json:"manifest_hash"`
	Author        string    `json:"author"`
	Message       string    `json:"message"`
	CreatedAt     time.Time `json:"created_at"`
	AutoGenerated bool      `json:"auto_generated"`
	PushedBy      string    `json:"pushed_by"` // account id
	PushedAt      time.Time `json:"pushed_at"`
}

type Tag struct {
	TreeID    string    `json:"tree_id"`
	Name      string    `json:"name"`
	Target    string    `json:"target"` // snapshot id
	Message   string    `json:"message"`
	Tagger    string    `json:"tagger"`
	CreatedAt time.Time `json:"created_at"`
}

// StagedSnapshot is a WIP snapshot visible to the team but not part of
// branch history. At most one per (tree, account, branch): a newer stage
// replaces the older one.
type StagedSnapshot struct {
	SnapshotID    string    `json:"snapshot_id"`
	TreeID        string    `json:"tree_id"`
	TenantID      string    `json:"tenant_id"`
	AccountID     string    `json:"account_id"`
	Author        string    `json:"author"`
	BranchName    string    `json:"branch_name"`
	FilesChanged  []string  `json:"files_changed"`
	FilesAdded    uint32    `json:"files_added"`
	FilesModified uint32    `json:"files_modified"`
	FilesDeleted  uint32    `json:"files_deleted"`
	Message       string    `json:"message"`
	StagedAt      time.Time `json:"staged_at"`
}

// BranchProtection applies to every branch whose name matches Pattern
// (path.Match glob, e.g. "main" or "release/*").
type BranchProtection struct {
	TreeID            string   `json:"tree_id"`
	Pattern           string   `json:"pattern"`
	NoDirectPush      bool     `json:"no_direct_push"`     // changes only via merge requests
	RequiredApprovals int      `json:"required_approvals"` // for MR merge
	AllowedPushers    []string `json:"allowed_pushers"`    // usernames; empty = role-based only
	NoDelete          bool     `json:"no_delete"`
}

type Approval struct {
	AccountID string    `json:"account_id"`
	Username  string    `json:"username"`
	At        time.Time `json:"at"`
}

type MergeRequest struct {
	ID             string     `json:"id"`
	TreeID         string     `json:"tree_id"`
	Number         int        `json:"number"` // per-tree, starts at 1
	Title          string     `json:"title"`
	Description    string     `json:"description"`
	SourceBranch   string     `json:"source_branch"`
	TargetBranch   string     `json:"target_branch"`
	AuthorID       string     `json:"author_id"`
	Author         string     `json:"author"`
	State          string     `json:"state"`
	Approvals      []Approval `json:"approvals"`
	CreatedAt      time.Time  `json:"created_at"`
	UpdatedAt      time.Time  `json:"updated_at"`
	MergedAt       *time.Time `json:"merged_at,omitempty"`
	MergedSnapshot string     `json:"merged_snapshot,omitempty"`
}

type AuditEvent struct {
	ID           string            `json:"id"`
	TenantID     string            `json:"tenant_id"`
	ActorID      string            `json:"actor_id"`
	Actor        string            `json:"actor"`  // username, "anonymous" or "system"
	Action       string            `json:"action"` // e.g. "branch.push", "tree.create", "auth.login"
	ResourceType string            `json:"resource_type"`
	ResourceID   string            `json:"resource_id"`
	Details      map[string]string `json:"details,omitempty"`
	RemoteAddr   string            `json:"remote_addr,omitempty"`
	At           time.Time         `json:"at"`
}

type AuditFilter struct {
	TenantID string
	ActorID  string
	Action   string // exact match; "" = any
	Since    time.Time
	Limit    int // 0 = default (100)
}

// LicenseRule assigns an SPDX license to paths in a tree. Grant controls
// what non-owning tenants may do: "read-only", "modify", "redistribute".
type LicenseRule struct {
	TreeID   string `json:"tree_id"`
	PathGlob string `json:"path_glob"` // "**" style glob, '/'-separated
	SPDX     string `json:"spdx"`
	Grant    string `json:"grant"`
}

// Principal is the authenticated caller attached to a request context.
type Principal struct {
	AccountID string `json:"account_id"`
	Username  string `json:"username"`
	TenantID  string `json:"tenant_id"` // personal tenant
	IsAdmin   bool   `json:"is_admin"`
}

// Anonymous returns true for a nil principal.
func (p *Principal) Anonymous() bool { return p == nil }

// Event is published on the EventBus and streamed to clients over SSE.
type Event struct {
	Type     string    `json:"type"` // see Event* constants
	TenantID string    `json:"tenant_id"`
	TreeID   string    `json:"tree_id,omitempty"`
	Actor    string    `json:"actor,omitempty"`
	Payload  any       `json:"payload,omitempty"`
	At       time.Time `json:"at"`
}

const (
	EventSnapshotStaged = "snapshot.staged"
	EventStagedCleared  = "staged.cleared"
	EventBranchPushed   = "branch.pushed"
	EventBranchCreated  = "branch.created"
	EventTagPushed      = "tag.pushed"
	EventTreeCreated    = "tree.created"
	EventMROpened       = "mr.opened"
	EventMRApproved     = "mr.approved"
	EventMRMerged       = "mr.merged"
	EventMRClosed       = "mr.closed"
)

// EventFilter selects events for a subscriber. Empty fields match anything.
type EventFilter struct {
	TenantID string
	TreeID   string
	Types    []string
}

// ServerStats is returned by the admin stats endpoint.
type ServerStats struct {
	Tenants      int   `json:"tenants"`
	Accounts     int   `json:"accounts"`
	Trees        int   `json:"trees"`
	Branches     int   `json:"branches"`
	Snapshots    int   `json:"snapshots"`
	Staged       int   `json:"staged"`
	Objects      int64 `json:"objects"`
	StorageBytes int64 `json:"storage_bytes"`
}
