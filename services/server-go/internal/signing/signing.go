// Package signing manages accounts' Ed25519 signing keys and verifies
// snapshot signatures on push (docs/ENGINEERING_PLAN.md §13.6).
//
// Keys are documents of the "signing_keys" collection keyed by
// DocKey(accountID, keyID); "signing_key_index" maps both the key id and
// the fingerprint to {account_id, id}, so signatures may name a key by
// either (clients sign with the fingerprint until the key is registered).
//
// The signed payload is the deterministic protobuf encoding of the
// snapshot's SnapshotRecord with signature, signing_key_id, tree_id and
// branch_name cleared — byte-for-byte what the Rust SDK's
// signing::signed_payload produces (both sides pin a shared test vector).
package signing

import (
	"context"
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/base64"
	"errors"
	"fmt"
	"log/slog"
	"slices"
	"strings"
	"time"
	"unicode/utf8"

	"github.com/google/uuid"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/known/timestamppb"

	"github.com/seanfilimon/worktree/services/server-go/internal/domain"
	"github.com/seanfilimon/worktree/services/server-go/internal/meta"
	"github.com/seanfilimon/worktree/services/server-go/internal/objstore"
	"github.com/seanfilimon/worktree/services/server-go/internal/proto/syncpb"
	"github.com/seanfilimon/worktree/services/server-go/internal/review"
)

// Document collections (ENGINEERING_PLAN §13.14).
const (
	CollKeys  = "signing_keys"
	CollIndex = "signing_key_index"
)

// AlgorithmEd25519 is the only supported key algorithm.
const AlgorithmEd25519 = "ed25519"

// KindSignatureRequired is the PushDenied kind of signature rejections.
const KindSignatureRequired = "signature_required"

// AuditSignatureInvalid is audited when a push carries a snapshot whose
// signature does not verify (or an unsigned snapshot on a RequireSigned
// branch).
const AuditSignatureInvalid = "snapshot.signature_invalid"

// maxKeyName bounds key names.
const maxKeyName = 100

// Deps are the collaborators of the signing package. Store is required;
// the others may be nil unless documented otherwise.
type Deps struct {
	Store   domain.MetaStore
	Objects objstore.Store
	History domain.History
	Authz   domain.Authorizer
	Bus     domain.EventBus
	Audit   domain.AuditLog
	Logger  *slog.Logger
}

// Service is the signing component. It implements domain.PushChecker.
type Service struct {
	d   Deps
	now func() time.Time
}

var _ domain.PushChecker = (*Service)(nil)

// New returns a Service.
func New(d Deps) *Service {
	if d.Logger == nil {
		d.Logger = slog.Default()
	}
	return &Service{d: d, now: func() time.Time { return time.Now().UTC() }}
}

// indexEntry is a signing_key_index document.
type indexEntry struct {
	AccountID string `json:"account_id"`
	ID        string `json:"id"`
}

// Fingerprint is "SHA256:" + unpadded standard base64 of sha256(pub).
func Fingerprint(pub []byte) string {
	sum := sha256.Sum256(pub)
	return "SHA256:" + base64.RawStdEncoding.EncodeToString(sum[:])
}

// ---- payload ------------------------------------------------------------

// Payload returns the bytes a signature of s covers.
func Payload(s *domain.Snapshot) ([]byte, error) {
	rec := &syncpb.SnapshotRecord{
		Id:            &syncpb.SnapshotId{Value: s.ID},
		ManifestHash:  &syncpb.ContentHash{Value: append([]byte(nil), s.ManifestHash[:]...)},
		Author:        s.Author,
		Message:       s.Message,
		AutoGenerated: s.AutoGenerated,
	}
	for _, p := range s.Parents {
		rec.Parents = append(rec.Parents, &syncpb.SnapshotId{Value: p})
	}
	if !s.CreatedAt.IsZero() {
		rec.CreatedAt = timestamppb.New(s.CreatedAt)
	}
	for _, d := range s.Dependencies {
		rec.Dependencies = append(rec.Dependencies, &syncpb.Dependency{
			TenantSlug: d.TenantSlug,
			Tree:       d.Tree,
			Branch:     d.Branch,
			Title:      d.Title,
			Details:    d.Details,
			Priority:   d.Priority,
			Blocking:   d.Blocking,
			Linked:     d.Linked,
		})
	}
	if s.Reverts != "" {
		rec.Reverts = &syncpb.SnapshotId{Value: s.Reverts}
	}
	return marshalPayload(rec)
}

// PayloadFromRecord returns the bytes a signature of rec covers.
func PayloadFromRecord(rec *syncpb.SnapshotRecord) ([]byte, error) {
	c := proto.Clone(rec).(*syncpb.SnapshotRecord)
	c.Signature = nil
	c.SigningKeyId = ""
	c.TreeId = nil
	c.BranchName = ""
	return marshalPayload(c)
}

func marshalPayload(rec *syncpb.SnapshotRecord) ([]byte, error) {
	b, err := proto.MarshalOptions{Deterministic: true}.Marshal(rec)
	if err != nil {
		return nil, fmt.Errorf("signing: encode payload: %w", err)
	}
	return b, nil
}

// ---- keys ---------------------------------------------------------------

func invalidf(format string, args ...any) error {
	return fmt.Errorf("%s: %w", fmt.Sprintf(format, args...), domain.ErrInvalid)
}

// Register stores a new public key of the caller's account. A public key
// may be registered once (ErrAlreadyExists otherwise, even after revoke).
func (s *Service) Register(ctx context.Context, p *domain.Principal, name, algorithm string, pub []byte) (*domain.SigningKey, error) {
	if p == nil || p.AccountID == "" || p.IsServiceAccount() {
		return nil, fmt.Errorf("only user accounts can register signing keys: %w", domain.ErrForbidden)
	}
	name = strings.TrimSpace(name)
	switch {
	case name == "":
		return nil, invalidf("name is required")
	case utf8.RuneCountInString(name) > maxKeyName || !utf8.ValidString(name):
		return nil, invalidf("name must be at most %d characters", maxKeyName)
	}
	if algorithm == "" {
		algorithm = AlgorithmEd25519
	}
	if algorithm != AlgorithmEd25519 {
		return nil, invalidf("unsupported algorithm %q (only %s)", algorithm, AlgorithmEd25519)
	}
	if len(pub) != ed25519.PublicKeySize {
		return nil, invalidf("public_key must be %d bytes (base64), got %d", ed25519.PublicKeySize, len(pub))
	}
	k := &domain.SigningKey{
		ID:          uuid.NewString(),
		AccountID:   p.AccountID,
		Name:        name,
		Algorithm:   AlgorithmEd25519,
		PublicKey:   append([]byte(nil), pub...),
		Fingerprint: Fingerprint(pub),
		CreatedAt:   s.now(),
	}
	idx := indexEntry{AccountID: k.AccountID, ID: k.ID}
	if err := s.d.Store.CreateDoc(ctx, CollIndex, k.Fingerprint, idx); err != nil {
		if errors.Is(err, domain.ErrAlreadyExists) {
			return nil, fmt.Errorf("public key %s is already registered: %w", k.Fingerprint, domain.ErrAlreadyExists)
		}
		return nil, err
	}
	if err := s.d.Store.CreateDoc(ctx, CollIndex, k.ID, idx); err != nil {
		return nil, err
	}
	if err := s.d.Store.CreateDoc(ctx, CollKeys, domain.DocKey(k.AccountID, k.ID), k); err != nil {
		return nil, err
	}
	return k, nil
}

// List returns the keys of an account (revoked keys included), oldest
// first.
func (s *Service) List(ctx context.Context, accountID string) ([]domain.SigningKey, error) {
	keys, err := meta.ListDocsT[domain.SigningKey](ctx, s.d.Store, CollKeys, meta.DocPrefix(accountID))
	if err != nil {
		return nil, err
	}
	slices.SortFunc(keys, func(a, b domain.SigningKey) int {
		if c := a.CreatedAt.Compare(b.CreatedAt); c != 0 {
			return c
		}
		return strings.Compare(a.ID, b.ID)
	})
	return keys, nil
}

// Revoke marks a key of accountID revoked (idempotent). ErrNotFound when
// the account has no such key.
func (s *Service) Revoke(ctx context.Context, accountID, id string) (*domain.SigningKey, error) {
	var out *domain.SigningKey
	err := meta.UpdateDocT(ctx, s.d.Store, CollKeys, domain.DocKey(accountID, id), func(cur *domain.SigningKey) (*domain.SigningKey, error) {
		if cur == nil {
			return nil, fmt.Errorf("signing key %q: %w", id, domain.ErrNotFound)
		}
		if cur.RevokedAt == nil {
			now := s.now()
			cur.RevokedAt = &now
		}
		out = cur
		return cur, nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}

// Resolve finds a key by id or fingerprint (ErrNotFound when unknown).
func (s *Service) Resolve(ctx context.Context, keyID string) (*domain.SigningKey, error) {
	if keyID == "" {
		return nil, fmt.Errorf("signing key: %w", domain.ErrNotFound)
	}
	idx, err := meta.GetDocT[indexEntry](ctx, s.d.Store, CollIndex, keyID)
	if err != nil {
		return nil, err
	}
	return meta.GetDocT[domain.SigningKey](ctx, s.d.Store, CollKeys, domain.DocKey(idx.AccountID, idx.ID))
}

// errBadSignature marks verification failures (as opposed to store errors).
var errBadSignature = errors.New("invalid signature")

// Verify checks the signature of snap against its registered, unrevoked
// key and returns that key. Failures wrap errBadSignature with a reason.
func (s *Service) Verify(ctx context.Context, snap *domain.Snapshot) (*domain.SigningKey, error) {
	if len(snap.Signature) == 0 {
		return nil, fmt.Errorf("%w: snapshot is not signed", errBadSignature)
	}
	key, err := s.Resolve(ctx, snap.SigningKeyID)
	if errors.Is(err, domain.ErrNotFound) {
		return nil, fmt.Errorf("%w: unknown signing key %q", errBadSignature, snap.SigningKeyID)
	}
	if err != nil {
		return nil, err
	}
	if key.RevokedAt != nil {
		return nil, fmt.Errorf("%w: signing key %s is revoked", errBadSignature, key.ID)
	}
	if len(key.PublicKey) != ed25519.PublicKeySize || len(snap.Signature) != ed25519.SignatureSize {
		return nil, fmt.Errorf("%w: malformed key or signature", errBadSignature)
	}
	payload, err := Payload(snap)
	if err != nil {
		return nil, err
	}
	if !ed25519.Verify(ed25519.PublicKey(key.PublicKey), payload, snap.Signature) {
		return nil, fmt.Errorf("%w: signature does not match key %s", errBadSignature, key.ID)
	}
	return key, nil
}

// IsBadSignature reports whether err is a verification failure.
func IsBadSignature(err error) bool { return errors.Is(err, errBadSignature) }

// ---- push check ---------------------------------------------------------

// CheckPushPlan implements domain.PushChecker: every new snapshot carrying
// a signature must verify against a registered, unrevoked key and is then
// marked Verified; on branches protected with RequireSigned every new
// snapshot must be verified.
func (s *Service) CheckPushPlan(ctx context.Context, p *domain.Principal, tree *domain.Tree, plan *domain.PushPlan) error {
	requireSigned, err := s.requireSigned(ctx, tree.ID, plan.Branch)
	if err != nil {
		return err
	}
	used := map[string]*domain.SigningKey{}
	for _, snap := range plan.NewSnapshots {
		snap.Verified = false // only this check may set it
		if len(snap.Signature) == 0 && snap.SigningKeyID == "" {
			if requireSigned {
				s.auditInvalid(ctx, p, tree, plan.Branch, snap, "unsigned")
				return &domain.PushDenied{
					Kind:   KindSignatureRequired,
					Reason: fmt.Sprintf("branch '%s' requires signed snapshots: snapshot %s is not signed", plan.Branch, snap.ID),
				}
			}
			continue
		}
		key, err := s.Verify(ctx, snap)
		if err != nil {
			if !IsBadSignature(err) {
				return err
			}
			s.auditInvalid(ctx, p, tree, plan.Branch, snap, err.Error())
			return &domain.PushDenied{
				Kind:   KindSignatureRequired,
				Reason: fmt.Sprintf("snapshot %s has an invalid signature", snap.ID),
			}
		}
		snap.Verified = true
		used[domain.DocKey(key.AccountID, key.ID)] = key
	}
	for docKey := range used {
		s.touch(ctx, docKey)
	}
	return nil
}

// requireSigned reports whether a protection matching branch requires
// signed snapshots.
func (s *Service) requireSigned(ctx context.Context, treeID, branch string) (bool, error) {
	rules, err := s.d.Store.ListProtections(ctx, treeID)
	if err != nil {
		return false, fmt.Errorf("signing: list protections: %w", err)
	}
	for _, r := range rules {
		if r.RequireSigned && review.MatchPattern(r.Pattern, branch) {
			return true, nil
		}
	}
	return false, nil
}

// touch records LastUsedAt on a key (best effort).
func (s *Service) touch(ctx context.Context, docKey string) {
	err := meta.UpdateDocT(ctx, s.d.Store, CollKeys, docKey, func(cur *domain.SigningKey) (*domain.SigningKey, error) {
		if cur == nil {
			return nil, domain.ErrNotFound
		}
		now := s.now()
		cur.LastUsedAt = &now
		return cur, nil
	})
	if err != nil {
		s.d.Logger.WarnContext(ctx, "signing: update last_used_at failed", "key", docKey, "err", err)
	}
}

func (s *Service) auditInvalid(ctx context.Context, p *domain.Principal, tree *domain.Tree, branch string, snap *domain.Snapshot, reason string) {
	if s.d.Audit == nil {
		return
	}
	e := domain.AuditEvent{
		ID:           uuid.NewString(),
		TenantID:     tree.TenantID,
		Actor:        "anonymous",
		Action:       AuditSignatureInvalid,
		ResourceType: "snapshot",
		ResourceID:   snap.ID,
		Details: map[string]string{
			"tree":     tree.Name,
			"branch":   branch,
			"snapshot": snap.ID,
			"key_id":   snap.SigningKeyID,
			"reason":   reason,
		},
		At: s.now(),
	}
	if p != nil {
		e.ActorID, e.Actor = p.AccountID, p.Username
	}
	s.d.Audit.Record(context.WithoutCancel(ctx), e)
}
