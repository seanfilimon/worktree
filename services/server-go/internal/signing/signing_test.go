func TestCheckPushPlan(t *testing.T) {
	ctx := context.Background()
	k := newKey(t, 4)
	revokedKey := newKey(t, 5)

	type tc struct {
		name          string
		requireSigned bool
		build         func(t *testing.T, f *fixture, key, revoked *domain.SigningKey) *domain.Snapshot
		denied        bool
		verified      bool
	}
	cases := []tc{
		{name: "unsigned allowed", build: func(t *testing.T, f *fixture, _, _ *domain.SigningKey) *domain.Snapshot {
			return newSnap(f.tree.ID)
		}},
		{name: "valid by id", verified: true, build: func(t *testing.T, f *fixture, key, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			sign(t, s, k, key.ID)
			return s
		}},
		{name: "valid by fingerprint", verified: true, requireSigned: true, build: func(t *testing.T, f *fixture, key, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			sign(t, s, k, key.Fingerprint)
			return s
		}},
		{name: "tampered", denied: true, build: func(t *testing.T, f *fixture, key, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			sign(t, s, k, key.ID)
			s.Message = "rewritten"
			return s
		}},
		{name: "wrong key", denied: true, build: func(t *testing.T, f *fixture, key, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			sign(t, s, newKey(t, 9), key.ID)
			return s
		}},
		{name: "unknown key", denied: true, build: func(t *testing.T, f *fixture, _, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			sign(t, s, k, "no-such-key")
			return s
		}},
		{name: "revoked key", denied: true, build: func(t *testing.T, f *fixture, _, revoked *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			sign(t, s, revokedKey, revoked.ID)
			return s
		}},
		{name: "truncated signature", denied: true, build: func(t *testing.T, f *fixture, key, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			sign(t, s, k, key.ID)
			s.Signature = s.Signature[:10]
			return s
		}},
		{name: "key id without signature", denied: true, build: func(t *testing.T, f *fixture, key, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			s.SigningKeyID = key.ID
			return s
		}},
		{name: "unsigned on require_signed", requireSigned: true, denied: true, build: func(t *testing.T, f *fixture, _, _ *domain.SigningKey) *domain.Snapshot {
			return newSnap(f.tree.ID)
		}},
		{name: "client cannot claim verified", build: func(t *testing.T, f *fixture, _, _ *domain.SigningKey) *domain.Snapshot {
			s := newSnap(f.tree.ID)
			s.Verified = true
			return s
		}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()
			f := newFixture(t)
			key, err := f.svc.Register(ctx, alice, "laptop", "", pubOf(k))
			must(t, err)
			revoked, err := f.svc.Register(ctx, bob, "old", "", pubOf(revokedKey))
			must(t, err)
			_, err = f.svc.Revoke(ctx, bob.AccountID, revoked.ID)
			must(t, err)
			if c.requireSigned {
				must(t, f.store.PutProtection(ctx, &domain.BranchProtection{TreeID: f.tree.ID, Pattern: "ma*", RequireSigned: true}))
			}
			snap := c.build(t, f, key, revoked)
			plan := &domain.PushPlan{Branch: "main", NewTip: snap.ID, NewSnapshots: []*domain.Snapshot{snap}}
			err = f.svc.CheckPushPlan(ctx, alice, f.tree, plan)
			var denied *domain.PushDenied
			if c.denied {
				if !errors.As(err, &denied) || denied.Kind != signing.KindSignatureRequired {
					t.Fatalf("err = %v, want signature_required", err)
				}
				if !strings.Contains(denied.Reason, snap.ID) {
					t.Fatalf("reason %q does not name the snapshot", denied.Reason)
				}
				if f.audit.count(signing.AuditSignatureInvalid) != 1 {
					t.Fatalf("audit = %+v", f.audit.events)
				}
				return
			}
			must(t, err)
			if snap.Verified != c.verified {
				t.Fatalf("verified = %v, want %v", snap.Verified, c.verified)
			}
			if c.verified {
				got, err := f.svc.Resolve(ctx, key.ID)
				must(t, err)
				if got.LastUsedAt == nil {
					t.Fatal("last_used_at not recorded")
				}
			}
		})
	}
}

