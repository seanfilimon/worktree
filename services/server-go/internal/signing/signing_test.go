func (allowAll) RoleOf(context.Context, string, string) (string, error) { return domain.RoleOwner, nil }

func TestPushVerifiesSignatures(t *testing.T) {
	f := newFixture(t)
	ctx := context.Background()
	objects := objstore.New(t.TempDir())
	syncSvc := syncsvc.New(syncsvc.Deps{
		Store:      f.store,
		Objects:    objects,
		History:    meta.NewHistory(f.store),
		Authz:      allowAll{},
		Audit:      f.audit,
		PushChecks: []domain.PushChecker{f.svc},
	})
	k := newKey(t, 6)
	key, err := f.svc.Register(ctx, alice, "laptop", "", pubOf(k))
	must(t, err)

	// One manifest object shared by every snapshot.
	mdata, err := proto.MarshalOptions{Deterministic: true}.Marshal(&syncpb.ManifestRecord{})
	must(t, err)
	mh := hash.Sum(mdata)
	must(t, objects.Put(ctx, mh, mdata))

	clock := time.Date(2026, 5, 1, 0, 0, 0, 0, time.UTC)
	record := func(parent string) *syncpb.SnapshotRecord {
		clock = clock.Add(time.Minute)
		rec := &syncpb.SnapshotRecord{
			Id:           &syncpb.SnapshotId{Value: uuid.NewString()},
			TreeId:       &syncpb.TreeId{Value: f.tree.ID},
			BranchName:   "main",
			ManifestHash: &syncpb.ContentHash{Value: mh[:]},
			Author:       "alice",
			Message:      "commit",
			CreatedAt:    timestamppb.New(clock),
		}
		if parent != "" {
			rec.Parents = []*syncpb.SnapshotId{{Value: parent}}
		}
		return rec
	}
	signRec := func(rec *syncpb.SnapshotRecord, keyID string) {
		payload, err := signing.PayloadFromRecord(rec)
		must(t, err)
		rec.Signature = ed25519.Sign(k, payload)
		rec.SigningKeyId = keyID
	}
	push := func(branch string, rec *syncpb.SnapshotRecord) *syncpb.PushResponse {
		t.Helper()
		resp, err := syncSvc.Push(iam.WithPrincipal(ctx, alice), &syncpb.PushRequest{
			TreeId:     &syncpb.TreeId{Value: f.tree.ID},
			BranchName: branch,
			NewTip:     rec.GetId(),
			Snapshots:  []*syncpb.SnapshotRecord{rec},
		})
		must(t, err)
		return resp
	}
	stored := func(id string) *domain.Snapshot {
		t.Helper()
		s, err := f.store.GetSnapshot(ctx, id)
		must(t, err)
		return s
	}
	denied := func(resp *syncpb.PushResponse) string {
		t.Helper()
		if resp.GetAccepted() {
			t.Fatal("push accepted, want rejection")
		}
		return resp.GetRejectionReason().GetAccessDenied().GetReason()
	}

	// Valid signature (by fingerprint, as an unregistered client would).
	first := record("")
	signRec(first, key.Fingerprint)
	if resp := push("main", first); !resp.GetAccepted() {
		t.Fatalf("valid push rejected: %v", resp.GetRejectionReason())
	}
	if s := stored(first.GetId().GetValue()); !s.Verified || s.SigningKeyID != key.Fingerprint {
		t.Fatalf("stored = %+v", s)
	}

	// Missing signature: accepted, not verified.
	second := record(first.GetId().GetValue())
	if resp := push("main", second); !resp.GetAccepted() {
		t.Fatalf("unsigned push rejected: %v", resp.GetRejectionReason())
	}
	if stored(second.GetId().GetValue()).Verified {
		t.Fatal("unsigned snapshot marked verified")
	}

	// Invalid signature: rejected and audited.
	bad := record(second.GetId().GetValue())
	signRec(bad, key.ID)
	bad.Message = "tampered after signing"
	if reason := denied(push("main", bad)); !strings.Contains(reason, "invalid signature") {
		t.Fatalf("reason = %q", reason)
	}
	if _, err := f.store.GetSnapshot(ctx, bad.GetId().GetValue()); !errors.Is(err, domain.ErrNotFound) {
		t.Fatalf("rejected snapshot stored: %v", err)
	}
	if f.audit.count(signing.AuditSignatureInvalid) != 1 {
		t.Fatal("signature_invalid not audited")
	}

	// RequireSigned: unsigned rejected, signed accepted.
	must(t, f.store.PutProtection(ctx, &domain.BranchProtection{TreeID: f.tree.ID, Pattern: "main", RequireSigned: true}))
	unsigned := record(second.GetId().GetValue())
	if reason := denied(push("main", unsigned)); !strings.Contains(reason, "requires signed") {
		t.Fatalf("reason = %q", reason)
	}
	signed := record(second.GetId().GetValue())
	signRec(signed, key.ID)
	if resp := push("main", signed); !resp.GetAccepted() {
		t.Fatalf("signed push rejected: %v", resp.GetRejectionReason())
	}
	if !stored(signed.GetId().GetValue()).Verified {
		t.Fatal("signed snapshot not verified")
	}

	// A revoked key no longer verifies.
	_, err = f.svc.Revoke(ctx, alice.AccountID, key.ID)
	must(t, err)
	after := record(signed.GetId().GetValue())
	signRec(after, key.ID)
	denied(push("main", after))
}
