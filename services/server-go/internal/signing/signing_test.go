func TestRegisterListRevoke(t *testing.T) {
	f := newFixture(t)
	ctx := context.Background()
	k := newKey(t, 1)
	key, err := f.svc.Register(ctx, alice, "  laptop ", "", pubOf(k))
	must(t, err)
	if key.Name != "laptop" || key.Algorithm != signing.AlgorithmEd25519 || key.AccountID != alice.AccountID {
		t.Fatalf("key = %+v", key)
	}
	if key.Fingerprint != signing.Fingerprint(pubOf(k)) {
		t.Fatalf("fingerprint = %s", key.Fingerprint)
	}
	// Resolvable by id and by fingerprint.
	for _, id := range []string{key.ID, key.Fingerprint} {
		got, err := f.svc.Resolve(ctx, id)
		must(t, err)
		if got.ID != key.ID {
			t.Fatalf("resolve %s = %s", id, got.ID)
		}
	}
	if _, err := f.svc.Resolve(ctx, "nope"); !errors.Is(err, domain.ErrNotFound) {
		t.Fatalf("resolve unknown: %v", err)
	}

	// Duplicate public keys are refused, also for other accounts.
	if _, err := f.svc.Register(ctx, bob, "copy", "", pubOf(k)); !errors.Is(err, domain.ErrAlreadyExists) {
		t.Fatalf("duplicate: %v", err)
	}
	cases := []struct {
		name, alg string
		pub       []byte
		p         *domain.Principal
		want      error
	}{
		{"", "", pubOf(newKey(t, 2)), alice, domain.ErrInvalid},
		{strings.Repeat("x", 101), "", pubOf(newKey(t, 2)), alice, domain.ErrInvalid},
		{"k", "rsa", pubOf(newKey(t, 2)), alice, domain.ErrInvalid},
		{"k", "", []byte{1, 2, 3}, alice, domain.ErrInvalid},
		{"k", "", pubOf(newKey(t, 2)), &domain.Principal{Username: "sa:acme/ci", Kind: domain.PrincipalServiceAccount}, domain.ErrForbidden},
	}
	for i, tc := range cases {
		if _, err := f.svc.Register(ctx, tc.p, tc.name, tc.alg, tc.pub); !errors.Is(err, tc.want) {
			t.Fatalf("case %d: err = %v, want %v", i, err, tc.want)
		}
	}

	second, err := f.svc.Register(ctx, alice, "desktop", signing.AlgorithmEd25519, pubOf(newKey(t, 3)))
	must(t, err)
	keys, err := f.svc.List(ctx, alice.AccountID)
	must(t, err)
	if len(keys) != 2 {
		t.Fatalf("list = %+v", keys)
	}
	if other, _ := f.svc.List(ctx, bob.AccountID); len(other) != 0 {
		t.Fatalf("bob has keys: %+v", other)
	}

	revoked, err := f.svc.Revoke(ctx, alice.AccountID, second.ID)
	must(t, err)
	if revoked.RevokedAt == nil {
		t.Fatal("not revoked")
	}
	again, err := f.svc.Revoke(ctx, alice.AccountID, second.ID)
	must(t, err)
	if !again.RevokedAt.Equal(*revoked.RevokedAt) {
		t.Fatal("revoke is not idempotent")
	}
	if _, err := f.svc.Revoke(ctx, bob.AccountID, key.ID); !errors.Is(err, domain.ErrNotFound) {
		t.Fatalf("revoke foreign key: %v", err)
	}
}

