func TestCrossLanguageVector(t *testing.T) {
	priv := ed25519.NewKeyFromSeed(vectorSeed())
	pub := priv.Public().(ed25519.PublicKey)
	if got := hex.EncodeToString(pub); got != vectorPublicKey {
		t.Fatalf("public key = %s", got)
	}
	if got := signing.Fingerprint(pub); got != vectorFingerprint {
		t.Fatalf("fingerprint = %s", got)
	}
	fromRec, err := signing.PayloadFromRecord(vectorRecord())
	if err != nil {
		t.Fatal(err)
	}
	if got := hex.EncodeToString(fromRec); got != vectorPayload {
		t.Fatalf("payload from record = %s", got)
	}
	fromSnap, err := signing.Payload(vectorSnapshot())
	if err != nil {
		t.Fatal(err)
	}
	if got := hex.EncodeToString(fromSnap); got != vectorPayload {
		t.Fatalf("payload from snapshot = %s", got)
	}
	if got := hex.EncodeToString(ed25519.Sign(priv, fromSnap)); got != vectorSignature {
		t.Fatalf("signature = %s", got)
	}
	// The input record is not modified.
	if vectorRecord().GetSigningKeyId() != "stale" {
		t.Fatal("record mutated")
	}
}

func TestPayloadOptionalFields(t *testing.T) {
	s := vectorSnapshot()
	s.Dependencies, s.Reverts, s.Parents = nil, "", nil
	got, err := signing.Payload(s)
	if err != nil {
		t.Fatal(err)
	}
	rec := vectorRecord()
	rec.Dependencies, rec.Reverts, rec.Parents = nil, nil, nil
	want, err := signing.PayloadFromRecord(rec)
	if err != nil {
		t.Fatal(err)
	}
	if hex.EncodeToString(got) != hex.EncodeToString(want) {
		t.Fatal("payloads differ without optional fields")
	}
}

